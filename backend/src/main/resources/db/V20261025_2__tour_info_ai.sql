-- AI가 신뢰할 수 있는 출처(공식 홈페이지 등)에서 조사한 관광지 이용정보.
-- TourAPI 원본(TB_TRMA_TOUR_INTRO)과 분리해 저장하고, 번역은 TB_TRMA_TOUR_TRANS에서 별도로 관리한다.
--  STATUS_CD: FOUND(출처 확인된 값) / NOT_FOUND(신뢰할 수 있는 출처를 찾지 못함 — 값은 노출하지 않음)
--  INFO_TEXT는 한국어(SRC_LANG_CD='ko')로 저장한다. 영어/일본어는 이 값을 원문으로 번역한다.
CREATE TABLE IF NOT EXISTS TB_TRMA_TOUR_INFO_AI (
    TOUR_ID      VARCHAR(200) NOT NULL,
    FIELD_NM     VARCHAR(50)  NOT NULL,
    STATUS_CD    VARCHAR(20)  NOT NULL,
    INFO_TEXT    TEXT         NULL,
    SRC_LANG_CD  VARCHAR(10)  NOT NULL DEFAULT 'ko',
    SOURCE_URL   VARCHAR(1000) NULL,
    SOURCE_TITLE VARCHAR(500) NULL,
    CHECKED_DT   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CREATE_DT    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATE_DT    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (TOUR_ID, FIELD_NM)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
